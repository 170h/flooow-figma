export function t(
  key: MessageKey,
  params?: Record<string, string | number>,
  locale?: AppLocale
): string {
  const catalog = (locale || activeLocale) === 'en' ? EN : KO;
  let text = catalog[key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
